#!/usr/bin/env python3
"""Losslessly pack the original numeric font's repeated 16-bit rows."""
from pathlib import Path
import itertools
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src/ui/resources/fonts/numfont16x22.c'
OUTPUT = SOURCE.with_name('numfont16x22_compact.h')

def generate(source):
    raw = source[source.index('const uint8_t numfont16x22[]'):]
    raw = re.sub(r'#if 0.*?#endif', '', raw, flags=re.S)
    rows = [int(v, 2) for v in re.findall(r'_BMP16\(0b([01]+)\)', raw)]
    assert rows and len(rows) % 22 == 0
    dictionary = sorted(set(rows))
    assert len(dictionary) + 22 <= 256
    offsets, data = [], []
    for offset in range(0, len(rows), 22):
        offsets.append(len(data))
        for value, group in itertools.groupby(rows[offset:offset+22]):
            count = len(list(group))
            data.append(dictionary.index(value))
            if count > 1:
                data.append(len(dictionary) + count - 2)
    result = '/* Generated by tools/pack_numfont.py; do not edit. */\n'
    result += f'#define NUMFONT_GLYPHS {len(offsets)}\n#define NUMFONT_ROWS {len(dictionary)}\n'
    for name, values, kind in [('numfont_rows', dictionary, 'uint16_t'),
                               ('numfont_offsets', offsets, 'uint16_t'),
                               ('numfont_packed', data, 'uint8_t')]:
        result += f'static const {kind} {name}[] = {{\n'
        for i in range(0, len(values), 12):
            result += '  ' + ','.join(str(v) for v in values[i:i+12]) + ',\n'
        result += '};\n'
    return result

if __name__ == '__main__':
    OUTPUT.write_bytes(generate(SOURCE.read_text(encoding='utf-8')).encode('utf-8'))
